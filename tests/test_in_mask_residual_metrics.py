"""Shadow-mode metric for lettering that survives inside the cleanup mask.

The removal verifier treats every masked pixel as flattened, so ghosts regenerated by
the reconstruction (dark remnants, outline echoes, flat-fill silhouettes) were never
measured. The metric is diagnostic only and must not change any decision.
"""

from test_support.offline_test_guard import install_offline_network_guard

install_offline_network_guard()

import unittest

import cv2
import numpy as np

import yomu.ocr.ocr_balloon as ob


def _scene():
    h, w = 120, 300
    x = np.arange(w, dtype=np.float32)[None, :]
    bg = np.repeat(np.repeat(200 + 50 * x / (w - 1), h, axis=0)[..., None], 3, axis=2).astype(np.uint8)
    glyph = np.zeros((h, w), np.uint8)
    cv2.putText(glyph, "GHOST", (20, 80), cv2.FONT_HERSHEY_SIMPLEX, 1.8, 255, 5, cv2.LINE_8)
    src = bg.copy(); src[glyph > 0] = 15
    mask = (cv2.dilate(glyph, np.ones((3, 3), np.uint8)) > 0).astype(np.uint8) * 255
    return bg, src, mask


class InMaskResidualMetricsTest(unittest.TestCase):
    def test_exact_reconstruction_has_no_residual_and_no_step(self):
        bg, src, mask = _scene()
        m = ob.in_mask_residual_metrics(src, bg, mask)
        self.assertEqual(m["status"], "measured")
        self.assertEqual(m["decision_impact"], "none")
        self.assertEqual(m["residual_pixels"], 0)
        self.assertLessEqual(m["boundary_step_excess"], 0.5)

    def test_flat_fill_on_gradient_shows_silhouette_step(self):
        bg, src, mask = _scene()
        flat = bg.copy(); flat[mask > 0] = 225
        m = ob.in_mask_residual_metrics(src, flat, mask)
        self.assertGreater(m["boundary_step_excess"], 5.0)

    def test_dark_remnant_inside_mask_is_counted(self):
        bg, src, mask = _scene()
        ghost = bg.copy()
        inner = cv2.erode(mask, np.ones((3, 3), np.uint8)) > 0
        ghost[inner] = 120
        m = ob.in_mask_residual_metrics(src, ghost, mask)
        self.assertGreater(m["residual_pixels"], 100)

    def test_missing_inputs_are_not_measured(self):
        _bg, src, mask = _scene()
        self.assertEqual(ob.in_mask_residual_metrics(src, None, mask)["status"], "not_measured")
        self.assertEqual(ob.in_mask_residual_metrics(src, src, np.zeros_like(mask))["status"], "not_measured")


if __name__ == "__main__":
    unittest.main()
